import { Calculator, Sparkles, AlertTriangle } from 'lucide-react'
import { Tooltip, TooltipTrigger, TooltipContent } from '../ui/tooltip'

type Method = 'manual' | 'calculated' | 'llm' | 'manual_fallback' | string | null

const METHOD_CONFIG: Record<string, { icon: React.ElementType; color: string; label: string }> = {
  calculated: {
    icon: Calculator,
    color: 'text-cyan-500/60',
    label: 'Calculated automatically from financial ratios',
  },
  llm: {
    icon: Sparkles,
    color: 'text-purple-500/60',
    label: 'Generated by AI model during monthly review',
  },
  manual_fallback: {
    icon: AlertTriangle,
    color: 'text-amber-500/60',
    label: 'Manual fallback — automated calculation failed',
  },
}

export function MethodIndicator({ method }: { method: Method }) {
  if (!method || method === 'manual') return null

  const config = METHOD_CONFIG[method]
  if (!config) return null

  const Icon = config.icon

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span className="inline-flex cursor-help">
          <Icon className={`h-3 w-3 ${config.color}`} />
        </span>
      </TooltipTrigger>
      <TooltipContent side="top">{config.label}</TooltipContent>
    </Tooltip>
  )
}
