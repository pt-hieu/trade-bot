-- Migration 313: schema_migrations tracking.
-- Source of truth for which migration files have been applied to this DB.
-- Idempotent: re-running the migration is a no-op.
--
-- TRUST MODEL for the backfill below: we insert a row for every .sql file
-- present on disk at the time 313 was authored, without verifying that
-- each target column, table, or index actually exists. Verified on
-- 2026-04-20 that only 306, 309, and 312 were unapplied outliers, and
-- all three have been applied. If a pre-313 migration was only partially
-- applied (e.g., a statement failed silently in the older apply_migrations
-- continue-on-error path), the backfill will mark it fully applied and
-- hide the drift. This is an accepted one-shot compromise. The runner
-- now fails fast on error, so all NEW partial applies surface immediately
-- without getting a phantom schema_migrations row.
--
-- New migrations starting 314 are recorded by the runner automatically.

