"""
Synthesis functions for combining analyses into final brief.

NOTE: The legacy synthesize_analyses() was removed in favor of
agents/synthesis.py::synthesize_with_agent() which uses tools for
selective data retrieval.
"""

import os
from datetime import UTC, datetime
from pathlib import Path

from pipeline.rendering.banners import Banner, render_banners


def _morning_sentinel(target_date: str) -> str:
    """SWI-134: trailer the collector uses to detect a complete brief."""
    run_id = os.environ.get("GITHUB_RUN_ID") or os.environ.get("LOGFIRE_TRACE_ID") or "local"
    ts = datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    return f"\n<!-- MORNING_COMPLETE: target_date={target_date} run_id={run_id} ts={ts} -->\n"


def save_morning_brief(
    content: str,
    research_dir: Path,
    today: str,
    banners: list[Banner] | None = None,
) -> Path:
    """
    Save the morning brief to file.

    Args:
        content: Brief content
        research_dir: Path to research directory
        today: Date string (YYYY-MM-DD)
        banners: Optional top-of-brief banners (critic-missing, streak alerts).

    Returns:
        Path to saved file
    """
    research_dir.mkdir(parents=True, exist_ok=True)
    output_file = research_dir / "morning-brief.md"

    banner_block = render_banners(banners or [])
    header = f"""# Morning Brief - {today}

*Generated by Kimi K2.5 at {datetime.now().strftime("%H:%M:%S")}*

---

"""
    sentinel = _morning_sentinel(today)
    body = header + banner_block + content + sentinel
    tmp_path = output_file.with_suffix(output_file.suffix + ".tmp")
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(body)
    os.replace(tmp_path, output_file)

    print(f"Saved: {output_file}")
    return output_file
