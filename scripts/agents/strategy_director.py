"""Strategy Director Agent — owns structured morning brief sections.

Generates both deterministic sections (GOAL PROGRESS, CAPITAL STATUS, etc.)
computed in Python, and qualitative sections (THEME, STANCE, MINDSET, etc.)
generated by the LLM. Synthesis embeds these sections verbatim.

Constraint computation is centralized in shared/rules/constraints.py and
pre-computed by the orchestrator before this agent runs.
"""

import asyncio
from datetime import date

from shared.rules.constraints import PipelineConstraints
from shared.rules.recommendation_gate import RecommendationGateDecision

from .strategy_sections import build_deterministic_sections


async def generate_strategy_directive(
    phase1_results: dict,
    phase2_results: dict,
    trading_mode: dict | None,
    pre_computed_constraints: PipelineConstraints,
    goals: list[dict],
    cash: dict,
    scan_date: date | None = None,
    pre_computed_picks: list[dict] | None = None,
    trailing_stops_context: str = "",
    geopolitical_context: str = "",
    portfolio_context: str = "",
    catalyst_context: str = "",
    catalyst_boost_context: str = "",
    articles_context: str = "",
    regime_context: str = "",
    macro_interpretation: str = "",
    commodity_context: str = "",
    vn_economy_context: str = "",
    recent_trades_context: str = "",
    learnings_context: str = "",
    memory_context: str = "",
    deterministic_sections: str | None = None,
    holdings_verb_summary: str = "",
    gate_decision: RecommendationGateDecision | None = None,
) -> tuple[str, str, PipelineConstraints]:
    """Generate structured strategy directive using split position/entry agents.

    Constraints are pre-computed by the orchestrator (compute_pipeline_constraints)
    and passed in — this agent no longer derives them.

    `deterministic_sections` may be pre-computed by the caller (phase_strategy
    pre-builds them so the fallback path can reuse the same string). When
    omitted, build here.

    Returns:
        Tuple of (position_guidance, entry_strategy, constraints_dict)
    """
    if scan_date is None:
        scan_date = date.today()

    constraints = pre_computed_constraints

    if deterministic_sections is None:
        deterministic_sections = await build_deterministic_sections(
            goals,
            cash,
            constraints,
            phase1_results,
        )

    # Run position_strategist and entry_strategist in parallel.
    # Use return_exceptions=True so a failure in one sub-agent does not cancel
    # the other mid-flight — that would force the outer phase_strategy retry
    # loop to re-run the innocent sub-agent on the next attempt, doubling LLM
    # cost. Re-raise the failing sub-agent's exception so the caller's
    # exception-type filter (UsageLimitExceeded / UnexpectedModelBehavior →
    # deterministic fallback) still applies.
    from .entry_strategist import generate_entry_strategy
    from .position_strategist import generate_position_guidance

    position_result, entry_result = await asyncio.gather(
        generate_position_guidance(
            phase2_results=phase2_results,
            trailing_stops_context=trailing_stops_context,
            scan_date=scan_date,
            geopolitical_context=geopolitical_context,
            portfolio_context=portfolio_context,
            regime_context=regime_context,
        ),
        generate_entry_strategy(
            phase1_results=phase1_results,
            phase2_results=phase2_results,
            trading_mode=trading_mode,
            deterministic_sections=deterministic_sections,
            pre_computed_picks=pre_computed_picks,
            scan_date=scan_date,
            catalyst_context=catalyst_context,
            catalyst_boost_context=catalyst_boost_context,
            articles_context=articles_context,
            macro_interpretation=macro_interpretation,
            commodity_context=commodity_context,
            vn_economy_context=vn_economy_context,
            regime_context=regime_context,
            recent_trades_context=recent_trades_context,
            learnings_context=learnings_context,
            memory_context=memory_context,
            holdings_verb_summary=holdings_verb_summary,
            gate_decision=gate_decision,
        ),
        return_exceptions=True,
    )

    if isinstance(position_result, BaseException):
        raise position_result
    if isinstance(entry_result, BaseException):
        raise entry_result

    position_guidance, entry_strategy = position_result, entry_result

    return position_guidance, entry_strategy, constraints
