def is_valid_ticker(ticker: str) -> bool:
    """Reject sector labels (LOGISTICS, PLASTICS) and malformed strings."""
    return bool(_TICKER_RE.match(ticker))


# SWI-125 Surface 7: shared sentinel set rejected at any ticker boundary
# (Pydantic validator, persist, render). Empty string included so the
# renderer can reject pre-validator legacy rows in a single membership check.
